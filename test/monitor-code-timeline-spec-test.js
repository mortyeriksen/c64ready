import assert from 'node:assert/strict';
import { CodeTimeline } from '../src/monitor/code-timeline.js';
const frame={lines:312,cyclesPerLine:63,eventCount:4,eventKind:[0x21,0x12,0x20,0x20],eventValue:[6,99,2,3],eventTick:[63,100,190,190],eventCPU:[1,0,1,1],eventPC:[0x3000,0,0x3003,0x3006],eventOpcode:[0x8d,0,0x8d,0x8d]};
const model=new CodeTimeline();model.setFrame(frame);
assert.equal(model.tick,63,'initial cursor opens the first recorded action');
model.filter('Colours');model.seek(100);
assert.equal(model.group,'Colours','scrubbing preserves the selected category');
assert.equal(model.action,null,'a filtered-out write does not appear as the selected action');
assert.deepEqual(model.lineIndices,[0],'line list contains only matching actions on the selected raster');
model.step(1);
assert.equal(model.tick,190,'Next action follows matching events rather than arbitrary cycle increments');
assert.equal(model.selected,2,'Next action selects the first event at a shared cycle');
model.step(1);
assert.equal(model.selected,3,'events sharing a cycle remain individually navigable');
model.step(-1);
assert.equal(model.selected,2,'Previous action reverses the event ordering even within one cycle');
model.seek(126);
assert.equal(model.action,null,'an empty cycle clears the previous explanation');
assert.deepEqual(model.lineIndices,[],'a line without matching writes has an empty action list');
model.step(-1);
assert.equal(model.tick,63,'Previous action searches before a cursor with no selected event');
model.seek(99999);
assert.equal(model.tick,19655,'frame cursor stays inside the PAL frame');
assert.equal(model.frame,frame,'navigation preserves captured frame identity');
model.seek(126);
model.setFrame({...frame,eventTick:[64,101,191,191]});
assert.equal(model.group,'Colours','automatic capture refresh preserves the selected category');
assert.equal(model.tick,126,'automatic capture refresh preserves the inspected frame position');
assert.equal(model.action,null,'refresh does not attach an unrelated action to the retained cursor');
model.setFrame({...frame,eventCount:0});
assert.equal(model.neighbour(1),-1,'an empty frame has no next action');
assert.equal(model.total,19656,'an empty action list still permits inspecting the complete frame budget');
model.setFrame(frame,{reset:true});
assert.equal(model.group,'All','a different machine resets the category');
assert.equal(model.tick,63,'a different machine opens its own first action');
model.setFrame(null);
assert.equal(model.frame,null,'clearing releases the captured frame');
assert.equal(model.actions.length,0,'clearing releases all captured actions');
console.log('ok  - shared captured-time cursor, persistent categories, empty cycles and ordered action stepping');

import assert from 'node:assert/strict';
import { voiceDescription, filterDescription, envelopePoints } from '../src/monitor/sound-model.js';
const r=new Uint8Array(64);
r[4]=65;r[2]=0;r[3]=8;r[0]=0x45;r[1]=0x1d;
assert.equal(voiceDescription(r,0,0).pulsePercent,50,'SID pulse width uses a 12-bit period of 4096 steps');
assert.equal(voiceDescription(r,0,0).note,'A4','PAL oscillator frequency maps near 440 Hz to A4');
r[4]=129;
assert.equal(voiceDescription(r,0,0).note,'','noise frequency is not represented as a heard musical note');
r[4]=19;
assert.equal(voiceDescription(r,0,0).note,'','sync makes a single oscillator note an unreliable sound description');
r[4]=80;
assert.equal(voiceDescription(r,0,0).wave,'Triangle + Pulse','combined waveforms preserve every selected bit');
r[23]=1;
assert.equal(voiceDescription(r,0,0).route,'Filter · no output mode','routing without an output mode is not described as audible filtering');
r[24]=144;
assert.equal(voiceDescription(r,0,2).route,'Bypass muted','voice 3 off suppresses the unfiltered path');
r[23]=5;
assert.equal(voiceDescription(r,0,2).route,'Filter','voice 3 off does not suppress the filtered path');
r[32+4]=33;r[32+24]=64;
assert.equal(voiceDescription(r,1,0).wave,'Saw','SID 2 voice control comes from its own register bank');
assert.match(filterDescription(r,1),/High-pass/,'SID 2 filter mode remains independent');
assert.equal(envelopePoints([0,0,15,0]),'0,38 24,6 48,6 76,6 100,38','maximum sustain illustration stays at the peak');
console.log('ok  - independent dual SID paths, pitch caveats, pulse percentage and envelope settings');

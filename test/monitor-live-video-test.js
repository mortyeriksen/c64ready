import assert from 'node:assert/strict';
import { liveVideoSetup } from '../src/monitor/live-video.js';

const state={vic:new Uint8Array(64),raster:0};
state.vic[0x11]=0x1b;state.vic[0x16]=8;
let view=liveVideoSetup(state);
assert.equal(view.x,32,'40-column comparator x24 maps to canvas x32');
assert.equal(view.width,320,'40-column window spans 320 pixels');
assert.equal(view.y,36,'25-row top raster 51 is picture row 36');
assert.equal(view.height,200,'25-row window ends before raster 251');
state.vic[0x11]=0x10;state.vic[0x16]=0;
view=liveVideoSetup(state);
assert.equal(view.x,39,'38-column comparator x31 maps to canvas x39');
assert.equal(view.width,304,'38-column window uses the asymmetric 31-to-335 comparators');
assert.equal(view.y,40,'24-row top raster 55 is picture row 40');
assert.equal(view.height,192,'24-row window ends before raster 247');
state.vic[0x11]=0x17;state.vic[0x16]=0x15;
view=liveVideoSetup(state);
assert.equal(view.scrollX,5,'fine X scroll uses D016 bits 0 through 2');
assert.equal(view.scrollY,7,'fine Y scroll uses D011 bits 0 through 2');
assert.equal(view.texture,'characters','multicolour text still uses the schematic character texture');
state.vic[0x11]=0x30;
assert.equal(liveVideoSetup(state).texture,'bitmap','bitmap mode selects the schematic bitmap texture');
state.vic[0x11]=0x70;
assert.equal(liveVideoSetup(state).texture,'none','invalid ECM and bitmap combination does not imply valid image data');
state.vic[0x11]=0x50;
assert.equal(liveVideoSetup(state).invalid,true,'ECM plus multicolour is identified as an invalid mode');
state.vic[0x11]=0;
assert.equal(liveVideoSetup(state).texture,'none','display enable off suppresses the schematic image texture');
state.vic[0x15]=0x81;state.vic[0x20]=0xf6;state.vic[0x21]=0xe2;
view=liveVideoSetup(state);
assert.equal(view.sprites,0x81,'sprite enable bits retain independent slots zero and seven');
assert.equal(view.border,6,'border colour uses the low nibble');
assert.equal(view.background,2,'background colour uses the low nibble');
const before=state.vic.slice();liveVideoSetup(state);
assert.deepEqual(state.vic,before,'visual interpretation leaves the detached snapshot unchanged');
console.log('ok  - live VIC setup geometry, mode validity, fine scroll and sprite enables');

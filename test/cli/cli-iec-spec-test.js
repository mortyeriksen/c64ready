import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseIecSpecs, plugIecDevices } from '../../cli/iec.mjs';
import { loadDeviceFile } from '../../cli/devices.mjs';
import { C64Machine } from '../../src/machine.js';
import { run } from '../../cli/run.mjs';
import { setQuiet } from '../../cli/report.mjs';
import { UsageError } from '../../cli/args.mjs';
import { readAsset, assetPath } from '../external-assets.js';
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'c64rdy-iec-'));
const printer = fileURLToPath(new URL('../../public/iec/printer.js', import.meta.url));
const led = fileURLToPath(new URL('../../public/userport/led-board.js', import.meta.url));
const probe = path.join(tmp, 'probe.mjs');
fs.writeFileSync(probe, `export const meta = { id: 'test.probe', name: 'Probe', version: '1', bus: 'iec', apiVersion: 1 };
export function create(port, host) { let frames = 0; host.onFrame(() => frames++); return { serialize: () => frames, exportOutput: () => '<svg/>', detach() { globalThis.__iecDetached = (globalThis.__iecDetached || 0) + 1; } }; }`);
try {
  assert.deepEqual(parseIecSpecs(['4:C:\\plugins\\printer.js', '30:other.js']).map(x => x.address), [4, 30], 'address parsing preserves Windows drive-letter paths');
  for (const spec of ['3:a.js', '8:a.js', '9:a.js', '31:a.js', '4:', '4.5:a.js', 'a.js']) assert.throws(() => parseIecSpecs([spec]), UsageError, `invalid or reserved address ${spec}`);
  assert.throws(() => parseIecSpecs(['4:a.js', '4:b.js']), UsageError, 'two plugins cannot use the same IEC address');
  assert.equal(parseIecSpecs(['4:a.svg', '4:a.html'], 'iec-output').length, 2, 'one device can export both formats');
  assert.equal((await loadDeviceFile(printer)).bus, 'iec', 'serve detects IEC metadata');
  assert.equal((await loadDeviceFile(led)).bus, 'userport', 'serve detects User Port metadata');
  await assert.rejects(loadDeviceFile(led, { bus: 'iec' }), /Expected an IEC device/);
  const m = new C64Machine(); m.reset(); m.attachUserport('other', () => ({}));
  const group = await plugIecDevices(m, parseIecSpecs([`4:${probe}`, `5:${probe}`]));
  assert.equal(m.iec.devices.size, 2, 'both IEC instances attach');
  group.frame(); group.frame();
  assert.equal(group.records[0].device.serialize(), 2, 'headless host frame hooks run');
  assert.notEqual(group.records[0].device, group.records[1].device, 'same plugin instances keep independent state');
  assert.equal(m.userport.deviceId, 'other', 'IEC devices preserve the User Port');
  assert.throws(() => group.validateOutputs([{ address: 6, file: 'x.svg' }]), /no IEC device/);
  assert.throws(() => group.validateOutputs([{ address: 4, file: 'x.pdf' }]), /svg or .html/);
  const output = path.join(tmp, 'export.svg');
  const outputs = [{ address: 4, file: output }];
  group.validateOutputs(outputs); group.writeOutputs(outputs, {});
  assert.equal(fs.readFileSync(output, 'utf8'), '<svg/>', 'the plugin supplies its own export');
  assert.throws(() => group.validateOutputs(outputs), /already exists/, 'output overwrite is refused');
  group.validateOutputs(outputs, { force: true });
  assert.throws(() => group.validateOutputs(outputs, { force: true }, output), /screenshot/, 'printer output cannot replace the screenshot');
  assert.throws(() => group.validateOutputs([{ address: 4, file: output }, { address: 5, file: output }], { force: true }), /distinct/);
  group.dispose(); group.dispose();
  assert.equal(globalThis.__iecDetached, 2, 'disposal is idempotent');
  assert.equal(m.iec, null, 'disposal releases the bus');
  assert.equal(m.userport.deviceId, 'other', 'disposal preserves User Port wiring');
  const throwing = path.join(tmp, 'throw.mjs');
  fs.writeFileSync(throwing, `export const meta = { id:'test.throw', name:'Throws', version:'1', bus:'iec', apiVersion:1 }; export function create(port) { port.wakeAt(port.now()+1); return { onTimer() { throw Error('boom'); } }; }`);
  const faults = await plugIecDevices(m, parseIecSpecs([`4:${throwing}`, `5:${probe}`]));
  m.iec.tick(); faults.frame();
  assert.throws(() => faults.check(), /IEC 4.*boom/, 'device faults are reported by address');
  assert.equal(faults.records[1].device.serialize(), 1, 'other devices survive a fault');
  faults.dispose();
  const bad = path.join(tmp, 'bad.mjs'); fs.writeFileSync(bad, 'export const meta = {};');
  await assert.rejects(plugIecDevices(m, parseIecSpecs([`4:${probe}`, `5:${bad}`])));
  assert.equal(m.iec, null, 'a partial attachment is cleaned up when a later plugin fails validation');
  console.log('ok - IEC arguments, connector detection, independent hosts, exports, overwrite rules and error cleanup');

  setQuiet(true);
  const fakePrg = path.join(tmp, 'empty.prg'); fs.writeFileSync(fakePrg, Buffer.from([1, 8, 0]));
  await assert.rejects(run([fakePrg, '--iec-output', '4:x.svg']), UsageError, 'output needs a corresponding IEC device');
  await assert.rejects(run([fakePrg, '--all', '--iec', `4:${probe}`]), UsageError);
  const tap = path.join(tmp, 'empty.tap'), header = Buffer.alloc(20); header.write('C64-TAPE-RAW'); header[12] = 1; fs.writeFileSync(tap, header);
  await assert.rejects(run([tap, '--iec', `4:${probe}`]), UsageError, 'device flags refuse unsupported tape runs');
  if (!readAsset('kernal') || !readAsset('basic') || !readAsset('chargen')) console.log('ok - KERNAL IEC print run # SKIP local C64 ROMs missing');
  else {
    const code = [0xa9,1,0xa2,4,0xa0,0,0x20,0xba,0xff,0xa9,0,0x20,0xbd,0xff,0x20,0xc0,0xff,0xa2,1,0x20,0xc9,0xff];
    for (const byte of Buffer.from('CLI<&')) code.push(0xa9,byte,0x20,0xd2,0xff);
    code.push(0x20,0xcc,0xff,0xa9,1,0x20,0xc3,0xff);
    const end = 0x080d + code.length; code.push(0x4c,end & 255,end >> 8);
    const prg = path.join(tmp, 'print.prg');
    fs.writeFileSync(prg, Buffer.from([1,8,0x0b,8,10,0,0x9e,...Buffer.from('2061'),0,0,0,...code]));
    const svg = path.join(tmp, 'printer.svg'), html = path.join(tmp, 'printer.html'), png = path.join(tmp, 'screen.png');
    await run([prg, '--iec', `4:${printer}`, '--iec', `5:${probe}`, '--userport', led,
      '--iec-output', `4:${svg}`, '--iec-output', `4:${html}`, '--frames', '35', '--no-press', '-o', png, '--roms', path.dirname(assetPath('kernal'))]);
    assert.match(fs.readFileSync(svg, 'utf8'), /CLI&lt;&amp;/, 'unmodified KERNAL output becomes safely escaped SVG');
    assert.match(fs.readFileSync(html, 'utf8'), /CLI&lt;&amp;/, 'the same job becomes printable HTML');
    assert.equal(fs.readFileSync(png).readUInt32BE(0), 0x89504e47, 'the emulator screenshot is still produced');
    console.log('ok - real CLI run prints over IEC with two plugins and User Port attached, producing SVG, HTML and PNG');
  }
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }

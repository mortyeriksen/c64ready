import assert from 'node:assert/strict';
import { C64Machine } from '../src/machine.js';
import { MachineFacade } from '../src/machine-facade.js';
import { graphicsLayout, spriteLayout, spritePixels, screenPixels } from '../src/monitor/setup-model.js';
import { decodeInstruction, registerMeaning, OPCODES } from '../src/monitor/disassembly.js';

const machine = new C64Machine(), facade = new MachineFacade(machine);
const state = facade.createInspectionState(), memory = machine.mem;
memory.basic = new Uint8Array(8192).fill(0xA5);
memory.kernal = new Uint8Array(8192).fill(0xE5);
memory.charRom = new Uint8Array(4096).fill(0xC5);
machine.vic2.charRom = memory.charRom;
memory.write(0, 0x2F); memory.write(1, 0x37);
memory.ram[0xA000] = 0x11; memory.ram[0xE000] = 0x22;
const bytes = new Uint8Array(2);
facade.copyCpuMemory(0xA000, bytes);
assert.equal(bytes[0], 0xA5, 'CPU view selects BASIC ROM with LORAM and HIRAM high');
assert.equal(facade.cpuMemorySource(0xA000), 'BASIC ROM', 'mapping describes visible BASIC ROM');
memory.write(1, 0x34);
facade.copyCpuMemory(0xA000, bytes);
assert.equal(bytes[0], 0x11, 'CPU view selects underlying RAM with LORAM and HIRAM low');
memory.write(1, 0x37);
machine.cia1.icrStatus = 1; machine.cia1.icrMask = 1;
machine.configureSecondSid({ enabled: true, address: 0xDE00 });
machine.mem.write(0xDE04, 0x21);
const before = machine.serializeState();
facade.inspectInto(state);
facade.copyCpuMemory(0, new Uint8Array(65536));
facade.copyVicMemory(0, new Uint8Array(16384), 0);
assert.deepEqual(machine.serializeState(), before, 'inspection preserves machine state, interrupt latches and SID bus state');
assert.equal(state.sid[36], 0x21, 'inspection copies second SID voice control into its separate register window');
state.vic[0] = 123; state.colorRam[0] = 12;
assert.notEqual(machine.vic2.regs[0], 123, 'inspection VIC buffer never aliases chip registers');
assert.notEqual(memory.colorRam[0], 12, 'inspection colour buffer never aliases colour RAM');
memory.ram[0x5000] = 0x51;
facade.copyVicMemory(0x1000, bytes, 0);
assert.equal(bytes[0], 0xC5, 'VIC bank zero exposes character ROM at local $1000');
facade.copyVicMemory(0x1000, bytes, 0x4000);
assert.equal(bytes[0], 0x51, 'VIC bank one exposes RAM at local $1000');
assert.equal(facade.vicMemorySource(0x1000, 0x8000), 'Character ROM', 'VIC bank two exposes the second character-ROM window');
memory.ram[0x7FFF] = 0x71; memory.ram[0x4000] = 0x41;
facade.copyVicMemory(0x3FFF, bytes, 0x4000);
assert.deepEqual([...bytes], [0x71, 0x41], 'VIC memory copy wraps inside the selected 16 KB bank');
assert.throws(() => facade.copyVicMemory(0, bytes, 0x1000), RangeError, 'VIC inspection rejects unaligned bank bases');
memory.cartMode = 'ultimax'; memory.cartRomHi = new Uint8Array(8192).fill(0xEA);
facade.copyVicMemory(0x3000, bytes, 0x4000);
assert.equal(bytes[0], 0xEA, 'Ultimax VIC view selects cartridge ROMH in its top 4 KB');
assert.equal(facade.vicMemorySource(0x3000, 0x4000), 'Cartridge ROM', 'Ultimax source is identified as cartridge ROM');
memory.cartMode = 'none';

const bank = new Uint8Array(16384);
state.vic.fill(0); state.vicBank = 0x8000; state.vic[0x18] = 0x24;
bank[0xBF8] = 0xC1;
state.vic[0x15] = 1; state.vic[0x10] = 1; state.vic[0] = 44; state.vic[1] = 20;
state.vic[0x17] = 1; state.vic[0x1D] = 1;
let sprite = spriteLayout(state, bank, 0);
assert.equal(sprite.pointerAddress, 0x8BF8, 'sprite pointer table is screen base plus $3F8');
assert.equal(sprite.address, 0xB040, 'sprite pointer selects a 64-byte slot in the VIC bank');
assert.equal(sprite.x, 300, 'sprite X combines low position and D010 high bit');
assert.equal(sprite.width, 48, 'horizontal expansion doubles the 24-pixel sprite width');
assert.equal(sprite.height, 42, 'vertical expansion doubles the 21-line sprite height');
state.spritePointers[0] = 0x40; state.spriteOffsets[0] = 0x1000; state.spriteBanks[0] = 0x4000;
sprite = spriteLayout(state, bank, 0, true);
assert.equal(sprite.address, 0x5000, 'last-fetched view uses the latched sprite bank rather than the current bank');

const spriteData = new Uint8Array(63), rgba = new Uint8ClampedArray(24 * 21 * 4);
spriteData[0] = 0b01101100;
state.vic[0x25] = 1; state.vic[0x26] = 3; state.palette[1] = 0x112233; state.palette[2] = 0x445566; state.palette[3] = 0x778899;
spritePixels(rgba, spriteData, { multicolour: true, colour: 2 }, state);
assert.deepEqual([...rgba.slice(0, 4)], [17, 34, 51, 255], 'sprite multicolour pair 01 selects D025');
assert.deepEqual([...rgba.slice(8, 12)], [68, 85, 102, 255], 'sprite multicolour pair 10 selects its own colour');
assert.deepEqual([...rgba.slice(16, 20)], [119, 136, 153, 255], 'sprite multicolour pair 11 selects D026');
assert.equal(rgba[27], 0, 'sprite multicolour pair 00 is transparent');

state.vic.fill(0); state.vic[0x18] = 0x18; state.vic[0x11] = 0x20;
state.palette[10] = 0xABCDEF; state.palette[3] = 0x123456;
bank.fill(0); bank[0x400] = 0xA3; bank[0x2000] = 0x80;
const screen = new Uint8ClampedArray(320 * 200 * 4);
screenPixels(screen, bank, state);
assert.deepEqual([...screen.slice(0, 3)], [171, 205, 239], 'hires bitmap set bit uses high screen-memory colour nibble');
assert.deepEqual([...screen.slice(4, 7)], [18, 52, 86], 'hires bitmap clear bit uses low screen-memory colour nibble');
assert.equal(graphicsLayout(state).bitmap, 0x2000, 'D018 bit three selects bitmap base $2000');

assert.equal(OPCODES.length, 256, 'all NMOS opcodes have a decoding entry');
let instruction = decodeInstruction(Uint8Array.of(0x8D, 0x20, 0xD0), 0, 0x1000);
assert.equal(instruction.name, 'STA', 'opcode $8D is absolute STA');
assert.equal(instruction.target, 0xD020, 'absolute operand is decoded little endian');
assert.equal(instruction.kind, 'write', 'STA is a write, not an observed execution event');
assert.equal(registerMeaning(instruction.target), 'Border colour', 'D020 controls VIC border colour');
instruction = decodeInstruction(Uint8Array.of(0xD0, 0xFC), 0, 0xFFFE);
assert.equal(instruction.target, 0xFFFC, 'relative branch target wraps after the two-byte instruction');
assert.equal(decodeInstruction(Uint8Array.of(0x0F, 0, 0x20), 0, 0).size, 3, 'undocumented absolute SLO has a three-byte encoding');
assert.equal(decodeInstruction(Uint8Array.of(0x6C, 0xFF, 0x20), 0, 0).target, null, 'indirect JMP operand is not presented as the resolved destination');
console.log('ok  - inspection preserves state and resolves CPU/VIC ROM, RAM and cartridge mappings');
console.log('ok  - sprite pointers, latched banks, expansion, multicolour pixels and bitmap colours');
console.log('ok  - CPU instruction decoding and register effect labels');
assert.equal(registerMeaning(0xDE04, 0xDE00), 'SID 2 voice 1 wave / gate', 'configured second SID window identifies its own voice register');

const { sidVoice } = await import('../src/monitor/sid-view.js');
const sidRegisters = new Uint8Array(64);
sidRegisters.set([0x34, 0x12, 0xAB, 0xFE, 0x75, 0xA3, 0xC7], 32);
const voice = sidVoice(sidRegisters, 32);
assert.equal(voice.frequency, 0x1234, 'SID frequency is a little-endian 16-bit register pair');
assert.equal(voice.pulse, 0xEAB, 'SID pulse threshold uses only 12 register bits');
assert.deepEqual(voice.adsr, [10, 3, 12, 7], 'ADSR settings decode the four nibbles independently');
assert.equal(voice.control, 0x75, 'SID waveform and control bits remain independent');
assert.equal(state.sidCount, 2, 'inspection exposes both configured SID chips');
assert.equal(state.sidModels[1], 1, 'second SID model is read independently');
console.log('ok  - SID oscillator, pulse, ADSR and dual-chip inspection');

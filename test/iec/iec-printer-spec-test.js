import assert from 'node:assert/strict';
import fs from 'node:fs';
import { importDeviceSource, validateIecModule } from '../../src/iec/plugins.js';
import { validateDeviceModule } from '../../src/userport/plugins.js';
const source = fs.readFileSync(new URL('../../public/iec/printer.js', import.meta.url), 'utf8');
const printer = await importDeviceSource(source);
const pages = printer.mpsPrinterPages;
assert.equal(validateIecModule(printer).address, 4);
assert.throws(() => validateDeviceModule(printer), /not a user port/);
assert.throws(() => validateIecModule({ meta: { ...printer.meta, address: 8 }, create() {} }), /excluding/);
assert.doesNotMatch(source, /^\s*import\s/m);
console.log('ok  - printer is an installable standalone IEC plugin with a separate bus contract');
const pixels = pages(Uint8Array.of(8, 129, 192));
assert.equal(pixels.pages[0][0].path, 'M0 0h12v10h-12zM12 60h12v10h-12z');
console.log('ok  - MPS bitmap pin 0 is at the top and pin 6 at the bottom, at 60 by 72 dpi');
assert.equal(pages(Uint8Array.of(8, 26, 3, 129)).pages[0][0].path, 'M0 0h12v10h-12zM12 0h12v10h-12zM24 0h12v10h-12z');
console.log('ok  - MPS repeat command repeats one graphic column');
const repeated = pages(Uint8Array.of(8, 26, 0, 129)).pages[0]?.[0]?.path || '';
assert.equal((repeated.match(/M/g) || []).length, 256, 'MPS-803 service manual 1-6: zero repeat count means 256 columns');
assert(repeated.endsWith('M3060 0h12v10h-12z'), '256 repeated columns span 256 horizontal dot positions');
console.log('ok  - MPS zero repeat count expands to 256 columns');
assert.equal(pages(Uint8Array.of(8, 129, 13, 129)).pages[0][0].path, 'M0 0h12v10h-12zM0 70h12v10h-12z');
console.log('ok  - MPS bitmap CR returns and advances exactly seven pin rows');
assert.equal(pages(Uint8Array.of(27, 16, 1, 2, 8, 129)).pages[0][0].path, 'M3096 0h12v10h-12z');
assert.equal(pages(Uint8Array.of(16, 49, 50, 65)).pages[0][0].x, 864);
console.log('ok  - MPS dot addresses are big endian and character tabs use decimal digits');
assert.equal(pages(Buffer.from('A\rB')).pages[0][1].y, 200);
assert.equal(pages(Uint8Array.of(17, 65)).pages[0][0].text, 'a');
assert.equal(pages(Uint8Array.of(14, 65)).pages[0][0].width, 144);
assert.equal(pages(Uint8Array.of(8, 26)).incomplete, true);
assert.equal(pages(Buffer.from('A\fB')).pages.length, 2);
console.log('ok  - MPS text spacing, business case, width, partial commands and browser page feeds');

import assert from 'node:assert/strict';
import { TapePulseWindow } from '../src/monitor/tape-pulses.js';
import { cartridgeWindows, reuFrameAccesses } from '../src/monitor/storage-analysis-model.js';
import { StorageHistory } from '../src/monitor/storage-model.js';
import { MachineFacade } from '../src/machine-facade.js';

const bytes=Uint8Array.of(48,0,0x18,0x02,0,67,85);
const deck={tapData:bytes,tapVersion:1,pos:bytes.length,recording:false,zeroGapCycles:20000};
const decoder=new TapePulseWindow();decoder.sample(deck,4);
assert.equal(decoder.offset,1,'TAP v1 extended entries must remain aligned when a decoding budget ends inside an entry');
assert.equal(decoder.pending,true,'A bounded scan reports that it has not reached the head');
assert.equal(decoder.window().length,0,'A pending scan never presents stale beginning-of-tape pulses as current');
decoder.sample(deck,4);decoder.sample(deck,4);
assert.deepEqual(decoder.window().map(p=>p.cycles),[384,536,536,680],'TAP v1 uses eight cycles per short byte and little-endian extended cycle counts');
assert.deepEqual(decoder.window().map(p=>p.offset),[0,1,5,6],'Pulse selection identifies complete encoded entries');
assert.deepEqual(bytes,Uint8Array.of(48,0,0x18,0x02,0,67,85),'Pulse inspection leaves the source bytes unchanged');
const held=decoder.window();decoder.sample(deck);
assert.deepEqual(decoder.window(),held,'An unchanged head position retains the same pulse timing');
deck.pos=1;decoder.sample(deck);
assert.deepEqual(decoder.window().map(p=>p.cycles),[384],'Seeking backwards excludes later pulse entries');
deck.pos=3;decoder.sample(deck);
assert.equal(decoder.incomplete,true,'A truncated four-byte entry is explicitly incomplete');
assert.deepEqual(decoder.window().map(p=>p.cycles),[384],'Incomplete TAP entries do not create pulse lengths');
deck.tapData=Uint8Array.of(0,1);deck.pos=2;deck.tapVersion=0;decoder.sample(deck);
assert.deepEqual(decoder.window().map(p=>p.cycles),[20000,8],'TAP v0 zero entries use the configured overflow duration');
deck.tapData=Uint8Array.of(1,2);deck.tapVersion=2;decoder.sample(deck);
assert.equal(decoder.version,2,'TAP v2 retains half-wave provenance for the renderer');
const recording=Uint8Array.of(2,0,0x34,0x12,0);let reads=0;
const rec={recording:true,recordedLength:1,tapVersion:1,recordedSlice:(from,to)=>{reads++;return recording.subarray(from,to);}};
decoder.sample(rec);rec.recordedLength=5;decoder.sample(rec);
assert.deepEqual(decoder.window().map(p=>p.cycles),[16,0x1234],'Recording decodes appended entries from valid boundaries in the recording stream');
assert.equal(reads,2,'Recording reads only through the provided facade slice method');
const large=new Uint8Array(100000).fill(1);decoder.sample({tapData:large,pos:large.length,tapVersion:1});
assert.equal(decoder.offset,32768,'Default pulse scanning bounds source traversal to 32768 bytes per observation');
for(let i=0;i<4;i++)decoder.sample({tapData:large,pos:large.length,tapVersion:1});
assert.equal(decoder.window().length,256,'Pulse windows have bounded retained storage even for very short pulses');
decoder.reset();assert.equal(decoder.buffer,null,'Closing the view releases the tape buffer reference');

const windows=cartridgeWindows({cpuMemorySource:address=>address>=0x8000&&address<0xa000||address>=0xe000?'Cartridge':'RAM'});
assert.deepEqual(windows.map(w=>[w.start,w.end]),[[0x8000,0xa000],[0xe000,0x10000]],'The map represents separate CPU-visible cartridge ranges without joining hidden memory');
assert.equal(cartridgeWindows({cpuMemorySource:()=> 'RAM'}).length,0,'A cartridge hidden from the CPU has no visible window');
const frame={lines:312,cyclesPerLine:63,provenance:{count:3,kind:[6,1,7],tick:[100,101,102],address:[0x2000,0x4000,0x2001],value:[12,99,34],aux:[0x02012345,0,0x02012346],overflow:false}};
const evidence=reuFrameAccesses(frame);
assert.equal(evidence.accesses.length,2,'REU evidence includes only actual REU bus reads and writes');
assert.deepEqual(evidence.accesses[0],{tick:100,write:false,address:0x2000,value:12,expansion:0x012345,command:2},'REU evidence separates command bits from the expansion address');
assert.equal(evidence.cycles,312*63,'REU access placement uses the captured frame geometry');
frame.provenance.overflow=true;
assert.equal(reuFrameAccesses(frame).incomplete,true,'Overflow marks REU counts as incomplete');
assert.equal(reuFrameAccesses(null).available,false,'Missing capture is distinguished from a frame with no REU activity');
const state=MachineFacade.prototype.createStorageInspection(),history=new StorageHistory();
state.drives[0].hardware=true;state.drives[0].hasMedia=true;state.drives[0].halfTrack=37;state.cartridge.inserted=true;state.cartridge.bank=4;history.sample(state,100);
assert.equal(history.heads[0][0],18.5,'Head history preserves half-track positions');
assert.equal(history.banks[0],4,'Bank history retains the actual sampled identifier');
assert.ok(Number.isNaN(history.heads[1][0]),'Absent mechanisms are gaps rather than track zero');
history.reset();assert.equal(history.banks[0],-1,'A new Monitor session discards prior cartridge history');
console.log('ok  - bounded TAP decoding, valid entry boundaries, recorded pulses, cartridge mappings and REU access evidence');

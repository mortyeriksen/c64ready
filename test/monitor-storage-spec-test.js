import assert from 'node:assert/strict';
import { C64Machine } from '../src/machine.js';
import { MachineFacade } from '../src/machine-facade.js';
import { Drive1541 } from '../src/drive1541.js';
import { createBlankD64 } from '../src/media/d64.js';
import { StorageHistory, reuSettings, activeStorageDevice } from '../src/monitor/storage-model.js';

const machine = new C64Machine(), facade = new MachineFacade(machine);
const state = facade.createStorageInspection();
const disk = createBlankD64('STORAGE TEST','01');
machine.setD64(disk); machine.truedriveEnabled = false;
facade.inspectStorageInto(state);
assert.equal(state.drives[0].hasMedia,true,'inserted media is visible without an attached true-drive mechanism');
assert.equal(state.drives[0].mode,'accelerated','disabled true-drive emulation identifies accelerated KERNAL loading');
assert.equal(state.drives[0].hardware,false,'a virtual drive is not reported as a physical mechanism');
machine.drive1541 = new Drive1541(new Uint8Array(16384), disk);
machine.truedriveEnabled = true; machine.drive1541.currentHalfTrack = 37;
facade.inspectStorageInto(state);
assert.equal(state.drives[0].mode,'true-drive','attached drive with true-drive enabled uses the hardware path');
assert.equal(state.drives[0].halfTrack,37,'half-track head positions are preserved without rounding');
machine.drive9Enabled = false; machine.setD64Drive9(createBlankD64('SECOND','02'));
facade.inspectStorageInto(state);
assert.equal(state.drives[1].available,false,'media in a disabled device does not imply a connected drive');
assert.equal(state.drives[1].hasMedia,true,'disconnected device and retained media are separate states');
machine.drive9Enabled = true;
facade.inspectStorageInto(state);
assert.equal(state.drives[1].mode,'accelerated','device 9 without a true-drive mechanism uses its virtual path when enabled');
machine.mem.setCartridge({mode:'8k',romLo:new Uint8Array(8192)});
machine.attachReu('1764');
const reu = machine.reu;
reu.ioWrite(0xDF02,0x00); reu.ioWrite(0xDF03,0x20);
reu.ioWrite(0xDF04,0); reu.ioWrite(0xDF05,0); reu.ioWrite(0xDF06,0);
reu.ioWrite(0xDF07,2); reu.ioWrite(0xDF08,0);
reu.ioWrite(0xDF09,0xC0); reu.ioWrite(0xDF01,0x90);
for (let i=0;i<20;i++) machine._runMasterCycle();
facade.newBlankTape();
const before = machine.serializeState();
facade.inspectStorageInto(state);
assert.deepEqual(machine.serializeState(),before,'storage inspection preserves CPU, drive, cartridge, tape and REU state including acknowledgement flags');
assert.equal(state.tape.hasMedia,true,'blank inserted tape is distinct from an empty deck');
assert.equal(state.reu.bytes,256*1024,'1764 reports its fitted 256 KB rather than its larger decoded address span');
assert.equal(state.reu.bankMask,7,'1764 has three decoded bank bits despite its four fitted 64 KB banks');
assert.equal(state.cartridge.inserted,true,'cartridge presence is independent of REU attachment');
assert.equal(state.cartridge.mode,'8k','CRT mapping is copied from the attached cartridge');
assert.equal(reuSettings(state.reu.registers,state.reu.bankMask).reu,2,'unused bank-register readback bits do not become address bits');
assert.equal(state.reu.registers[0] & 0xC0,0xC0,'side-effect-free REU inspection retains completion and pending IRQ flags');
state.reu.registers[0] = 0;
assert.equal(reu.ioPeek(0xDF00) & 0xC0,0xC0,'caller-owned REU register bytes never alias controller state');
facade.inspectStorageInto(state);
const history = new StorageHistory();
history.sample(state,0);
assert.equal(history.reuChanged,false,'first observation does not fabricate a transfer');
state.reu.activity++;
history.sample(state,100);
assert.equal(history.reuChanged,true,'increased activity counter records a transfer between observations');
state.reu.activity = 0;
history.sample(state,200);
assert.equal(history.reuChanged,false,'reset counters do not appear as new transfers');
state.reu.attached = false; history.sample(state,300);
state.reu.attached = true; state.reu.activity = 9; history.sample(state,400);
assert.equal(history.reuChanged,false,'attachment establishes a baseline without attributing earlier transfers');
for(let i=5;i<100;i++) history.sample(state,i*100);
assert.equal(history.count,81,'observation history retains eight seconds including both endpoints');
assert.equal(history.seconds,8,'history duration describes the actual observation window');
const registers = new Uint8Array(11); registers[1] = 3;
assert.equal(reuSettings(registers).length,65536,'zero REU transfer length encodes 65536 bytes');
assert.equal(reuSettings(registers).operation,'Compare memory','REU command bits 1:0 select compare without implying a copy');
facade.detachReu(); machine.mem.setCartridge(null); facade.ejectTape();
facade.inspectStorageInto(state);
assert.equal(state.reu.attached,false,'detached REU does not retain attached state');
assert.equal(state.reu.registers.some(value => value !== 0),false,'detached REU clears all copied register bytes');
assert.equal(state.cartridge.inserted,false,'cartridge ejection clears presence');
assert.equal(state.tape.hasMedia,false,'tape ejection clears media presence');
console.log('ok  - read-only storage snapshot, media/mode distinctions, CRT and REU state, bounded activity history');

const selection = facade.createStorageInspection();
selection.cartridge.inserted = true;
assert.equal(activeStorageDevice(selection),3,'Storage opens an inserted CRT when the drive slots are empty');
selection.reu.attached = true; selection.reu.active = true;
assert.equal(activeStorageDevice(selection,3),4,'an active REU transfer takes priority over an idle cartridge');
selection.reu.active = false; selection.tape.hasMedia = true; selection.tape.motor = true;
assert.equal(activeStorageDevice(selection,4),2,'a running tape takes priority over an idle attached REU');
selection.tape.motor = false;
assert.equal(activeStorageDevice(selection,4),4,'an attached selection is retained when all devices are idle');
selection.drives[1].led = true;
assert.equal(activeStorageDevice(selection,4),1,'drive nine activity selects drive nine');

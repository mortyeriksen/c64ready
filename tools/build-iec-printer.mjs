// Bundle the IEC printer and print-job UI into one installable module.
// Run after changing the printer, print-job controls or print-output renderer.
import { build } from 'vite';
import { writeFileSync } from 'node:fs';
const result = await build({ configFile: false, logLevel: 'silent', build: {
  write: false, minify: false, lib: { entry: 'src/iec/devices/printer.js', formats: ['es'], fileName: 'printer' },
  rolldownOptions: { output: { codeSplitting: false } },
} });
const chunk = result[0].output.find(item => item.type === 'chunk');
writeFileSync('public/iec/printer.js', '// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright © 2026 Morten Øien Eriksen\n// Generated by tools/build-iec-printer.mjs.\n' + chunk.code);
console.log('Built public/iec/printer.js');
